import { Hono } from "hono";
import { desc, eq } from "drizzle-orm";
import { db, schema } from "@erp/db";
import { renderDocumentHtml, type RenderInput } from "@erp/shared";
import type { AppEnv } from "../lib/types";
import { queue, queueEvents } from "../lib/queue";

export const documents = new Hono<AppEnv>();

documents.get("/list", async (c) => {
  const kind = c.req.query("kind") === "template" ? "template" : "document";
  const rows = await db.select().from(schema.document).where(eq(schema.document.kind, kind)).orderBy(desc(schema.document.updatedAt));
  return c.json(rows);
});

documents.get("/doc/:id", async (c) => {
  const [row] = await db.select().from(schema.document).where(eq(schema.document.id, c.req.param("id")));
  return row ? c.json(row) : c.json({ error: "Not found" }, 404);
});

documents.post("/doc", async (c) => {
  const b = (await c.req.json().catch(() => ({}))) as { title?: string; type?: string; content?: string };
  const [row] = await db
    .insert(schema.document)
    .values({ title: b.title || "Sans titre", type: (b.type as never) ?? "free", content: b.content ?? "", createdBy: c.get("user")?.id })
    .returning();
  return c.json(row, 201);
});

documents.patch("/doc/:id", async (c) => {
  const b = (await c.req.json().catch(() => ({}))) as { title?: string; content?: string; googleDocId?: string | null };
  const set: Record<string, unknown> = {};
  for (const k of ["title", "content", "googleDocId"] as const) if (b[k] !== undefined) set[k] = b[k];
  const [row] = await db.update(schema.document).set(set).where(eq(schema.document.id, c.req.param("id"))).returning();
  return row ? c.json(row) : c.json({ error: "Not found" }, 404);
});

export async function buildRenderInput(kind: "quote" | "invoice", id: string, locale: "fr" | "en" = "fr"): Promise<RenderInput | null> {
  const table = kind === "quote" ? schema.quote : schema.invoice;
  const [doc] = await db.select().from(table).where(eq(table.id, id));
  if (!doc) return null;
  const [entity] = await db.select().from(schema.legalEntity).where(eq(schema.legalEntity.id, doc.legalEntityId));
  const client = doc.organizationId ? (await db.select().from(schema.organization).where(eq(schema.organization.id, doc.organizationId)))[0] : null;
  const contactId = kind === "quote" ? (doc as typeof schema.quote.$inferSelect).contactId : null;
  const contact = contactId ? (await db.select().from(schema.person).where(eq(schema.person.id, contactId)))[0] : null;
  if (!entity) return null;
  const q = doc as typeof schema.quote.$inferSelect;
  const i = doc as typeof schema.invoice.$inferSelect;
  return {
    kind,
    locale,
    number: doc.number,
    title: doc.title,
    issueDate: doc.issueDate,
    dueDate: kind === "quote" ? q.validUntil : i.dueDate,
    currency: doc.currency,
    lines: doc.lines,
    taxes: doc.taxes.map(({ code, label, rate }) => ({ code, label, rate })),
    amountPaid: kind === "invoice" ? i.amountPaid : 0,
    introduction: kind === "quote" ? q.introduction : null,
    scope: kind === "quote" ? q.scope : null,
    terms: kind === "quote" ? q.terms : null,
    notes: kind === "invoice" ? null : null,
    entity,
    client,
    contactName: contact ? `${contact.firstName} ${contact.lastName ?? ""}`.trim() : null,
  };
}

/** HTML preview (same template the worker prints). */
documents.get("/:kind/:id/html", async (c) => {
  const kind = c.req.param("kind");
  if (kind !== "quote" && kind !== "invoice") return c.json({ error: "Unknown kind" }, 400);
  const input = await buildRenderInput(kind, c.req.param("id"), c.req.query("locale") === "en" ? "en" : "fr");
  if (!input) return c.json({ error: "Not found" }, 404);
  return c.html(renderDocumentHtml(input));
});

/** PDF generated by the worker (Chromium) through BullMQ. */
documents.get("/:kind/:id/pdf", async (c) => {
  const kind = c.req.param("kind");
  if (kind !== "quote" && kind !== "invoice") return c.json({ error: "Unknown kind" }, 400);
  const locale = c.req.query("locale") === "en" ? "en" : "fr";
  const input = await buildRenderInput(kind, c.req.param("id"), locale);
  if (!input) return c.json({ error: "Not found" }, 404);
  try {
    const table = kind === "quote" ? schema.quote : schema.invoice;
    const [rec] = await db.select({ org: table.organizationId, issueDate: table.issueDate }).from(table).where(eq(table.id, c.req.param("id")));
    const fileName = `${rec?.issueDate ?? new Date().toISOString().slice(0, 10)} — ${input.client?.name ?? "Client"} — ${kind === "quote" ? "Devis" : "Facture"} — ${input.number}.pdf`.replace(/[\/]/g, "-");
    const job = await queue.add("render-pdf", { kind, id: c.req.param("id"), html: renderDocumentHtml(input), organizationId: rec?.org ?? null, fileName }, { removeOnComplete: 50, removeOnFail: 50 });
    const result = (await job.waitUntilFinished(queueEvents, 45_000)) as { pdfBase64: string; url?: string | null };
    const buf = Buffer.from(result.pdfBase64, "base64");
    if (result.url) await db.update(table).set({ fileUrl: result.url }).where(eq(table.id, c.req.param("id")));
    return new Response(buf, {
      headers: {
        "content-type": "application/pdf",
        "content-disposition": `inline; filename="${input.number}.pdf"`,
      },
    });
  } catch (e) {
    return c.json({ error: `Génération PDF indisponible : ${(e as Error).message}` }, 503);
  }
});

/** Converts an accepted quote into a draft invoice. */
documents.post("/quote/:id/invoice", async (c) => {
  const [q] = await db.select().from(schema.quote).where(eq(schema.quote.id, c.req.param("id")));
  if (!q) return c.json({ error: "Not found" }, 404);
  const { nextNumber } = await import("../lib/data");
  const n = await nextNumber("invoice", q.legalEntityId);
  const [inv] = await db
    .insert(schema.invoice)
    .values({
      number: n.number,
      title: q.title,
      legalEntityId: q.legalEntityId,
      organizationId: q.organizationId,
      projectId: q.projectId,
      quoteId: q.id,
      status: "draft",
      issueDate: new Date().toISOString().slice(0, 10),
      dueDate: new Date(Date.now() + 30 * 864e5).toISOString().slice(0, 10),
      currency: q.currency,
      lines: q.lines,
      taxes: q.taxes,
      subtotal: q.subtotal,
      taxTotal: q.taxTotal,
      total: q.total,
    })
    .returning();
  return c.json(inv, 201);
});
